"""Desafío 99: Simulación climática con tuplas



Utilizando tuplas para registrar datos inmutables, crea una simulación básica del clima en diferentes ciudades. cada registro será una tupla (ciudad, temperatura, humedad). el programa debe:



almacenar múltiples registros climáticos.


determinar la ciudad con la temperatura más alta y más baja.


calcular el promedio general de humedad.
"""

# Almacenamiento de múltiples registros climáticos en una lista de tuplas
registros_climaticos = [
    ("Montevideo", 22.5, 65),
    ("Salto", 28.0, 50),
    ("Rocha", 18.2, 80),
    ("Rivera", 26.5, 55),
    ("Maldonado", 19.0, 75)
]

def analizar_clima(registros):
    if not registros:
        return None, None, 0.0

    # Determinar la ciudad con temperatura más alta y más baja
    # Usamos la posición [1] de la tupla (temperatura) como criterio
    ciudad_mas_calurosa = max(registros, key=lambda x: x[1])
    ciudad_mas_fria = min(registros, key=lambda x: x[1])

    # Calcular el promedio general de humedad (posición [2] de la tupla)
    suma_humedad = sum(registro[2] for registro in registros)
    promedio_humedad = suma_humedad / len(registros)

    return ciudad_mas_calurosa[0], ciudad_mas_fria[0], promedio_humedad

calurosa, fria, promedio_h = analizar_clima(registros_climaticos)

print(f"Ciudad más calurosa: {calurosa}")
print(f"Ciudad más fría: {fria}")
print(f"Promedio general de humedad: {promedio_h:.2f}%")

"""Desafío 100: Análisis deportivo con conjuntos



Una federación deportiva registra participantes en varios torneos mediante conjuntos. desarrolla un programa para:



identificar atletas que participaron en todos los torneos del año.


detectar atletas que participaron exclusivamente en un único torneo.


calcular la cantidad total de atletas únicos que compitieron durante el año.
"""

# Torneos representados como conjuntos de nombres de atletas
torneo_ajedrez = {"Sofía", "Lucas", "Mateo", "Valentina"}
torneo_atletismo = {"Lucas", "Valentina", "Martina"}
torneo_natacion = {"Sofía", "Lucas", "Valentina", "Joaquín"}

lista_torneos = [torneo_ajedrez, torneo_atletismo, torneo_natacion]

# 1. Atletas que participaron en TODOS los torneos del año (Intersección)
atletas_todos = set.intersection(*lista_torneos)

# 2. Atletas que participaron exclusivamente en un ÚNICO torneo
# Un atleta es exclusivo si está en un torneo y en ningún otro de la lista
atletas_unicos_torneo = set()
for i, torneo_actual in enumerate(lista_torneos):
    # Unir todos los demás torneos
    otros_torneos = set.union(*(lista_torneos[:i] + lista_torneos[i+1:]))
    # Diferencia: atletas que están en este torneo pero NO en los demás
    exclusivos_este = torneo_actual - otros_torneos
    atletas_unicos_torneo.update(exclusivos_este)

# 3. Cantidad total de atletas únicos que compitieron durante el año (Unión)
todos_los_atletas = set.union(*lista_torneos)
cantidad_total_unicos = len(todos_los_atletas)

print("Atletas en todos los torneos:", atletas_todos)
print("Atletas exclusivos de un solo torneo:", atletas_unicos_torneo)
print("Cantidad total de atletas únicos:", cantidad_total_unicos)

"""Desafío 101: Historial médico inmutable



Een un hospital, cada registro médico se representa como una tupla inmutable (fecha, paciente, diagnóstico). construye un programa que permita:



almacenar múltiples registros médicos.


consultar el historial completo de un paciente específico.


contar cuántos diagnósticos distintos han sido registrados en total.
"""

# Almacenamiento de múltiples registros médicos
historiales_medicos = [
    ("2026-03-01", "Juan Pérez", "Hipertensión"),
    ("2026-03-05", "María Gómez", "Diabetes Tipo 2"),
    ("2026-04-12", "Juan Pérez", "Control de rutina"),
    ("2026-05-20", "Carlos Ruiz", "Asma"),
    ("2026-06-10", "María Gómez", "Hipertensión")
]

# 1. Consultar el historial completo de un paciente específico
def consultar_historial(registros, nombre_paciente):
    return [reg for reg in registros if reg[1].lower() == nombre_paciente.lower()]

# 2. Contar cuántos diagnósticos distintos han sido registrados en total
def contar_diagnosticos_distintos(registros):
    # Extraemos los diagnósticos (posición 2) utilizando un conjunto para evitar duplicados
    diagnosticos_unicos = {reg[2] for reg in registros}
    return len(diagnosticos_unicos), diagnosticos_unicos

# Pruebas de funcionamiento
paciente_buscado = "Juan Pérez"
historial_juan = consultar_historial(historiales_medicos, paciente_buscado)
total_diag, lista_diag = contar_diagnosticos_distintos(historiales_medicos)

print(f"Historial de {paciente_buscado}:")
for registro in historial_juan:
    print(f"  - Fecha: {registro[0]} | Diagnóstico: {registro[2]}")

print(f"\nCantidad de diagnósticos distintos registrados: {total_diag}")
print(f"Diagnósticos únicos: {lista_diag}")

